-- Dataset de entrenamiento: varias grabaciones por seña.
--
-- Por qué hace falta: `senas.landmarks_referencia` guarda UNA sola
-- grabación por seña (la referencia contra la que compara el DTW). Para que
-- un modelo de machine learning aprenda una seña necesita muchas
-- grabaciones de esa seña, idealmente de varias personas distintas. Cada
-- fila de esta tabla es una de esas grabaciones.
--
-- Se guarda la captura CRUDA de MediaPipe (21 puntos por mano y por frame,
-- más el tamaño del video), no una versión ya normalizada: así cualquier
-- mejora futura del preprocesamiento o del modelo se puede recalcular sin
-- volver a grabar a nadie. Son solo coordenadas de puntos, nunca imágenes.
--
-- Solo los administradores pueden leer, agregar o borrar muestras (RLS).
-- Al eliminar una cuenta se eliminan también sus muestras (ON DELETE
-- CASCADE): es dato de la persona, no del proyecto.
--
-- Es seguro correr esta migración más de una vez.

CREATE TABLE IF NOT EXISTS public.muestras_sena (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sena_id bigint NOT NULL REFERENCES public.senas(id) ON DELETE CASCADE,
  autor_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  formato smallint NOT NULL DEFAULT 1,
  tipo text NOT NULL CHECK (tipo IN ('estatica', 'dinamica')),
  manos_requeridas smallint NOT NULL CHECK (manos_requeridas IN (1, 2)),
  ancho integer NOT NULL CHECK (ancho > 0),
  alto integer NOT NULL CHECK (alto > 0),
  duracion_ms integer NOT NULL CHECK (duracion_ms >= 0),
  total_frames integer NOT NULL CHECK (total_frames BETWEEN 1 AND 900),
  captura jsonb NOT NULL CHECK (coalesce(jsonb_typeof(captura -> 'frames'), '') = 'array' AND pg_column_size(captura) < 2000000),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS muestras_sena_sena_id_idx ON public.muestras_sena (sena_id);

ALTER TABLE public.muestras_sena ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'muestras_sena' AND policyname = 'Admins leen muestras') THEN
    CREATE POLICY "Admins leen muestras"
      ON public.muestras_sena
      FOR SELECT
      USING (EXISTS (SELECT 1 FROM public.profiles WHERE profiles.id = auth.uid() AND profiles.es_admin = true));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'muestras_sena' AND policyname = 'Admins agregan muestras propias') THEN
    CREATE POLICY "Admins agregan muestras propias"
      ON public.muestras_sena
      FOR INSERT
      WITH CHECK (
        autor_id = auth.uid()
        AND EXISTS (SELECT 1 FROM public.profiles WHERE profiles.id = auth.uid() AND profiles.es_admin = true)
      );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'muestras_sena' AND policyname = 'Admins borran muestras') THEN
    CREATE POLICY "Admins borran muestras"
      ON public.muestras_sena
      FOR DELETE
      USING (EXISTS (SELECT 1 FROM public.profiles WHERE profiles.id = auth.uid() AND profiles.es_admin = true));
  END IF;
END $$;
-- Sin política de UPDATE a propósito: una muestra mal grabada se borra y se graba de nuevo.
